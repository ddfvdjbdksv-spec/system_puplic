//  تم تعطيل هذا الملف بالكامل ضمن إصلاح نظام مزامنة الأجهزة.
//
//  السبب:
//    كان هذا الملف يحتوي نسخة قديمة من دوال:
//      uploadStudentsToCloud / downloadStudentsFromCloud /
//      uploadPaymentsToCloud / downloadPaymentsFromCloud
//    وكانت هذه النسخة تتصل بقاعدة بيانات Firebase الخاصة
//    بالمنصة (window.db) بدلاً من قاعدة بيانات مزامنة الأجهزة
//    المستقلة (window.deviceSyncDb).
//
//    ولأن index.html كان يُحمِّل هذا الملف بعد app.js، فإن
//    الدوال المعرَّفة هنا كانت تستبدل (override) الدوال الصحيحة
//    الأحدث والأكمل الموجودة في app.js — وهو ما كان يُسبب فشل
//    المزامنة بالكامل (لا رفع، لا استلام).
//
//  الوضع الحالي:
//    النسخة الصحيحة والكاملة من نظام مزامنة الأجهزة (رفع/استلام
//    الطلاب، رفع/استلام كل بيانات البرنامج) موجودة الآن فقط
//    داخل app.js، تحت قسم:
//        "مزامنة الأجهزة عبر Firebase — Device Sync"
//    وتستخدم بشكل صحيح قاعدة Firebase المستقلة عبر:
//        ensureDeviceSyncFirebaseInitialized()  →  window.deviceSyncDb
//
//    هذا الملف لم يعد مُدرَجاً في index.html، ويمكن حذفه نهائياً
//    من المشروع بأمان. تم إبقاؤه فارغاً (بدل حذفه من القرص) فقط
//    تحسبًا لوجود أي مرجع قديم له.
// ============================================================
